ALTER TABLE chats ADD COLUMN IF NOT EXISTS cities VARCHAR(500) NOT NULL DEFAULT 'Минск';
ALTER TABLE chats ADD COLUMN IF NOT EXISTS currencies VARCHAR(200) NOT NULL DEFAULT 'USD';
ALTER TABLE chats ADD COLUMN IF NOT EXISTS send_rates BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE chats ADD COLUMN IF NOT EXISTS send_weather BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE chats ADD COLUMN IF NOT EXISTS last_digest_date DATE;
ALTER TABLE chats ADD COLUMN IF NOT EXISTS weather_alerts BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS message_stats
(
    chat_id   BIGINT       NOT NULL,
    user_id   BIGINT       NOT NULL,
    user_name VARCHAR(200) NOT NULL,
    stat_day  DATE         NOT NULL,
    messages  INT          NOT NULL,
    PRIMARY KEY (chat_id, user_id, stat_day)
);

CREATE TABLE IF NOT EXISTS story_games
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id      BIGINT        NOT NULL,
    message_id   INT           NOT NULL,
    poll_id      VARCHAR(100)  NOT NULL UNIQUE,
    options      VARCHAR(2000) NOT NULL,
    answer_index INT,
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at    TIMESTAMP
);

CREATE TABLE IF NOT EXISTS story_votes
(
    game_id      BIGINT       NOT NULL,
    user_id      BIGINT       NOT NULL,
    user_name    VARCHAR(200) NOT NULL,
    option_index INT          NOT NULL,
    PRIMARY KEY (game_id, user_id)
);

CREATE TABLE IF NOT EXISTS story_options
(
    chat_id BIGINT PRIMARY KEY,
    options VARCHAR(2000) NOT NULL
);

ALTER TABLE story_games ADD COLUMN IF NOT EXISTS confirm_message_id INT;
ALTER TABLE story_games ADD COLUMN IF NOT EXISTS voters_snapshot INT;

CREATE TABLE IF NOT EXISTS story_confirmations
(
    game_id      BIGINT NOT NULL,
    user_id      BIGINT NOT NULL,
    option_index INT    NOT NULL,
    PRIMARY KEY (game_id, user_id)
);

CREATE TABLE IF NOT EXISTS chat_bots
(
    chat_id BIGINT NOT NULL,
    bot_id  BIGINT NOT NULL,
    PRIMARY KEY (chat_id, bot_id)
);

CREATE TABLE IF NOT EXISTS story_players
(
    chat_id BIGINT PRIMARY KEY,
    players INT NOT NULL
);